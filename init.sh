#!/usr/bin/env bash
# Vernissage – step 1: set up the environment and start the containers.
#
#   ./init.sh            interactive
#
# Asks for domain and port, generates all secrets into .env.local, creates the
# data directories, starts the stack with `docker compose up -d --build` and then
# runs ./install.sh (administrator account and instance settings).

source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"
cd "$ROOT_DIR"

printf '%s\n' "${C_BOLD}Vernissage – initialisation${C_RESET} ($ROOT_DIR)"

# ---------------------------------------------------------------------------
section "Prerequisites"

for cmd in openssl curl; do
    command -v "$cmd" >/dev/null 2>&1 || die "'$cmd' is missing. Install it with: sudo apt install -y $cmd"
done

if ! detect_docker; then
    if command -v docker >/dev/null 2>&1; then
        # Docker exists but is unusable – never install a second Docker on top of it.
        warn "Docker is installed but not reachable, or the Compose plugin is missing."
        info "Check: sudo systemctl status docker  ·  docker compose version"
        info "Compose plugin for Docker CE: sudo apt install docker-compose-plugin"
        die "Nothing has been changed. Please fix Docker and run ./init.sh again."
    fi
    warn "Docker is not installed."
    if command -v apt-get >/dev/null 2>&1 && confirm "Install Docker now via apt (docker.io + docker-compose-v2)?" n; then
        sudo apt-get update
        sudo apt-get install -y docker.io docker-compose-v2
        sudo systemctl enable --now docker
        detect_docker || die "Docker is still not running. Please check manually: sudo systemctl status docker"
    else
        die "Please install Docker and the Compose plugin (https://docs.docker.com/engine/install/ubuntu/) and run this script again."
    fi
fi
ok "Docker: $("${DOCKER[@]}" --version)"
ok "Compose: $("${DOCKER[@]}" compose version --short)"
[[ "${DOCKER[0]}" == sudo ]] && warn "Docker is being called via sudo (user is not in the 'docker' group)."

# ---------------------------------------------------------------------------
section "Configuration"

regenerate=true
if [[ -f "$ENV_FILE" ]]; then
    warn ".env.local already exists."
    if [[ -d "$ROOT_DIR/data/postgres" ]] && [[ -n "$(ls -A "$ROOT_DIR/data/postgres" 2>/dev/null)" ]]; then
        warn "data/ already contains data. New secrets would render the existing database unusable."
        info "The existing configuration will be reused."
        regenerate=false
    elif ! confirm "Regenerate it? (No = reuse the existing values)" n; then
        regenerate=false
    fi
fi

if [[ "$regenerate" == true ]]; then
    info "Domain of the instance, e.g. photos.example.org (without https://)."
    info "Note: the domain can practically never be changed later (Fediverse identities)."
    while true; do
        ask DOMAIN "Domain"
        DOMAIN="${DOMAIN#http://}"; DOMAIN="${DOMAIN#https://}"; DOMAIN="${DOMAIN%%/*}"
        DOMAIN="$(printf '%s' "$DOMAIN" | tr '[:upper:]' '[:lower:]')"
        [[ "$DOMAIN" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] && break
        warn "Invalid domain."
    done

    info ""
    info "Local port on which the host Nginx reaches the instance (127.0.0.1 only)."
    while true; do
        ask PROXY_PORT "Port" "8180"
        [[ "$PROXY_PORT" =~ ^[0-9]+$ ]] && (( PROXY_PORT >= 1 && PROXY_PORT <= 65535 )) || { warn "Invalid port."; continue; }
        if (ss -ltn 2>/dev/null || netstat -ltn 2>/dev/null) | awk '{print $4}' | grep -qE "[:.]${PROXY_PORT}\$"; then
            warn "Port $PROXY_PORT is already in use."
            confirm "Use it anyway?" n || continue
        fi
        break
    done

    ask MAX_UPLOAD_SIZE "Maximum upload size (Nginx format)" "40M"
    ask DOCKER_TAG "Vernissage image tag" "latest"

    # Derive the Compose project name from the directory name (allows several instances per server).
    PROJECT_NAME="$(basename "$ROOT_DIR" | tr '[:upper:]' '[:lower:]' | sed -e 's/[^a-z0-9_-]/-/g' -e 's/^[^a-z0-9]*//')"
    [[ -n "$PROJECT_NAME" ]] || PROJECT_NAME="vernissage"

    gen_vapid_keys

    umask 077
    cat > "$ENV_FILE" <<EOF
# Vernissage – generated by init.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# CONTAINS SECRETS – do not commit, do not share. (chmod 600)

COMPOSE_PROJECT_NAME=$PROJECT_NAME

# Instance
VERNISSAGE_DOMAIN=$DOMAIN
VERNISSAGE_BASEADDRESS=https://$DOMAIN
DOCKER_TAG=$DOCKER_TAG
LOG_LEVEL=info

# Internal proxy (target for the host Nginx)
PROXY_BIND=127.0.0.1
PROXY_PORT=$PROXY_PORT
MAX_UPLOAD_SIZE=$MAX_UPLOAD_SIZE

# PostgreSQL
POSTGRES_DB=vernissage
POSTGRES_USER=vernissage
POSTGRES_PASSWORD=$(gen_hex 24)

# Redis
REDIS_PASSWORD=$(gen_hex 24)

# MinIO / S3
MINIO_ROOT_USER=vernissage-$(gen_hex 4)
MINIO_ROOT_PASSWORD=$(gen_hex 24)
S3_BUCKET=vernissage

# Web Push
VPUSH_KEY=$(gen_hex 32)
WEBPUSH_VAPID_PUBLIC_KEY=$VAPID_PUBLIC_KEY
WEBPUSH_VAPID_PRIVATE_KEY=$VAPID_PRIVATE_KEY
EOF
    chmod 600 "$ENV_FILE"
    ok ".env.local written with new secrets."
fi

# .env -> .env.local, so that plain `docker compose …` picks up the values too.
if [[ ! -L "$ROOT_DIR/.env" ]]; then
    [[ -e "$ROOT_DIR/.env" ]] && die "A regular file named .env exists – please remove it (a symlink to .env.local will be created)."
    ln -s .env.local "$ROOT_DIR/.env"
fi

load_env
ok "Domain: $VERNISSAGE_DOMAIN  →  proxy: $PROXY_BIND:$PROXY_PORT  (project: $COMPOSE_PROJECT_NAME)"

# ---------------------------------------------------------------------------
section "Directories"

# Only create what is missing – existing directories may belong to container users.
for dir in data data/postgres data/redis data/minio backups nginx; do
    [[ -d "$ROOT_DIR/$dir" ]] && continue
    mkdir "$ROOT_DIR/$dir" 2>/dev/null \
        || die "Cannot create $dir/ as user '$(id -un)'. Check the ownership with: ls -la $ROOT_DIR $ROOT_DIR/data
  If data/ belongs to root, Docker created it because 'docker compose up' ran before ./init.sh.
  On a fresh installation fix it with: docker compose down && sudo rm -rf $ROOT_DIR/data"
done
for dir in data backups; do
    chmod 700 "$ROOT_DIR/$dir" 2>/dev/null || warn "Could not restrict the permissions of $dir/ (owned by another user)."
done
ok "data/, backups/ and nginx/ are in place."

# ---------------------------------------------------------------------------
section "Preparing storage (MinIO)"

info "Building MinIO from source (takes a few minutes the first time)…"
compose_noin build minio
compose_noin up -d minio
wait_healthy minio 180

if compose_noin run --rm -T s3-tools s3api head-bucket --bucket "$S3_BUCKET" >/dev/null 2>&1; then
    ok "Bucket '$S3_BUCKET' already exists."
else
    compose_noin run --rm -T s3-tools s3api create-bucket --bucket "$S3_BUCKET" >/dev/null
    ok "Bucket '$S3_BUCKET' created."
fi

policy="{\"Version\":\"2012-10-17\",\"Statement\":[{\"Sid\":\"VernissagePublicRead\",\"Effect\":\"Allow\",\"Principal\":{\"AWS\":[\"*\"]},\"Action\":[\"s3:GetObject\"],\"Resource\":[\"arn:aws:s3:::${S3_BUCKET}/*\"]}]}"
compose_noin run --rm -T s3-tools s3api put-bucket-policy --bucket "$S3_BUCKET" --policy "$policy" >/dev/null
ok "Public read access to objects granted (bucket listing remains blocked)."

# ---------------------------------------------------------------------------
section "Starting the stack"

compose_noin pull --ignore-buildable --quiet
compose_noin up -d --build

wait_healthy postgres 120
wait_healthy redis 60
wait_healthy api 600
wait_healthy jobs 300
wait_healthy web 180
wait_healthy push 120

if curl -fsS -o /dev/null --max-time 10 "http://127.0.0.1:${PROXY_PORT}/api/v1/health" -H 'Accept: application/json'; then
    ok "Proxy responds on http://127.0.0.1:${PROXY_PORT}"
else
    warn "Proxy on port ${PROXY_PORT} is not responding (yet) – see: docker compose logs proxy"
fi

compose_noin ps

# ---------------------------------------------------------------------------
section "Continuing with the installation"

if [[ -f "$INSTALLED_MARKER" ]]; then
    ok "Vernissage is already installed (data/.installed). Done."
    exit 0
fi

if confirm "Run ./install.sh now (administrator account and instance settings)?" y; then
    exec "$ROOT_DIR/install.sh"
else
    info "Run it later with: ./install.sh"
fi
